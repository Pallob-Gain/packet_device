// Generate reference frames using the existing Node.js implementation.
// Run: node rust-lib/tools/nodejs_oracle.cjs [--write]
// --write refreshes the checked-in fixture; without it the fixture is verified.
const fs = require('node:fs');
const path = require('node:path');
const PacketDevice = require('../../examples/NodeJS_Integration/lib/PacketDevice.js');
const Struct = require('../../examples/NodeJS_Integration/lib/struct.V4.js');

const lockType = Struct.makeType({ amplitude: Struct.type.float, phase: Struct.type.float });
const lock = new Struct(lockType);
lock.setJson({ amplitude: 5.0, phase: 0.5 });
const bioType = Struct.makeType({ age: Struct.type.uint8_t, height: Struct.type.uint8_t });
const bios = [{ age: 20, height: 150 }, { age: 21, height: 152 }].map(value => {
  const bio = new Struct(bioType);
  bio.setJson(value);
  return bio;
});
const massiveType = Struct.makeType({
  name: Struct.stringType(100),
  other_data: Struct.arrayType(Struct.type.float, 200),
});
const massive = new Struct(massiveType);
massive.set('name', 'Pallob Kumar Gain');
massive.set('other_data', Array.from({ length: 200 }, (_, i) => i / 2));

const frames = [
  ['command_vnr', PacketDevice.dataPacket('VNR', null)],
  ['scalar_amplitude', PacketDevice.dataPacket('amplitude', PacketDevice.getTypedValue(PacketDevice.Type.float, 5.0))],
  ['scalar_age', PacketDevice.dataPacket('age', PacketDevice.getTypedValue(PacketDevice.Type.uint8_t, 20))],
  ['scalar_signed', PacketDevice.dataPacket('signed', PacketDevice.getTypedValue(PacketDevice.Type.int32_t, -123456))],
  ['array_counts', PacketDevice.dataPacket('counts', new Float32Array([1.0, 2.5, -3.0]))],
  ['struct_ulx', PacketDevice.dataPacket('ULX', lock)],
  ['array_bio', PacketDevice.dataPacket('bio', bios)],
  ['struct_massive', PacketDevice.dataPacket('mdt', massive)],
  ['array_600', PacketDevice.dataPacket('large', Uint8Array.from({ length: 600 }, (_, i) => i & 255))],
  ['delimited_counts', PacketDevice.dataPacket('counts', new Float32Array([1.0, 2.5, -3.0]), '\r\n')],
];
const text = '# Generated by tools/nodejs_oracle.cjs using examples/NodeJS_Integration/lib.\n'
  + frames.map(([name, bytes]) => `${name} ${bytes.toString('hex')}`).join('\n') + '\n';
const fixture = path.join(__dirname, '../tests/fixtures/nodejs_frames.txt');
if (process.argv.includes('--write')) {
  fs.mkdirSync(path.dirname(fixture), { recursive: true });
  fs.writeFileSync(fixture, text);
  console.log(`Wrote ${frames.length} Node.js reference frames.`);
} else {
  if (fs.readFileSync(fixture, 'utf8').replace(/\r\n/g, '\n') !== text) {
    throw new Error('Reference frames changed. Review the protocol change before regenerating the fixture.');
  }
  console.log(`PASS: ${frames.length} fixtures match the existing Node.js implementation.`);
}
